# Pseudocode:
# 1. Ask the user to enter their name and store it in a variable called name
# 2. Ask the user to enter their age and store it in a variable called age
# 3. Ask the user to enter their house number and store it in a variable called house_number
# 4. Ask the user to enter their street name and store it in a variable called street_name
# 5. Print a single sentence with all these details in a structured format

# Python code:

# Step 1: Ask the user for their name
name = input("Please enter your name: ")

# Step 2: Ask the user for their age
age = input("Please enter your age: ")

# Step 3: Ask the user for their house number
house_number = input("Please enter your house number: ")

# Step 4: Ask the user for their street name
street_name = input("Please enter your street name: ")

# Step 5: Print a sentence containing all the details
print(f"This is {name}. They are {age} years old and live at house number {house_number} on {street_name}.")
